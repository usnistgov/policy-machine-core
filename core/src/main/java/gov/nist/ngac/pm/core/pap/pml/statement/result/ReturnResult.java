package gov.nist.ngac.pm.core.pap.pml.statement.result;

import java.util.Objects;

/**
 * Signals that a return statement was executed, carrying its value (or null) out to the caller.
 */
public class ReturnResult extends StatementResult{

    private Object value;

    public ReturnResult(Object value) {
        this.value = value;
    }

    public Object getValue() {
        return value;
    }

    public void setValue(Object value) {
        this.value = value;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) {
            return true;
        }
        if (!(o instanceof ReturnResult that)) {
            return false;
        }
        return Objects.equals(value, that.value);
    }

    @Override
    public int hashCode() {
        return Objects.hashCode(value);
    }
}
